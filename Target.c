void RenderTarget(Target_t *t) {
    int32_t dx = t->xPos - t->prevX;
    int32_t dy = t->yPos - t->prevY;

    // Erase Horizontal Tail
    if (dx > 0)      ST7735_FillRect(t->prevX, t->prevY - 15, dx, 16, ST7735_BLACK);
    else if (dx < 0) ST7735_FillRect(t->xPos + 16, t->prevY - 15, -dx, 16, ST7735_BLACK);

    // Erase Vertical Tail
    if (dy > 0)      ST7735_FillRect(t->xPos, t->prevY - 15, 16, dy, ST7735_BLACK);
    else if (dy < 0) ST7735_FillRect(t->xPos, t->yPos + 1, 16, -dy, ST7735_BLACK);
    
    // REDRAW target (Now only the edges were flickered/erased)
    ST7735_DrawBitmap(t->xPos, t->yPos, TargetAnimation[t->broken], 16, 16);
}


void Target_Update(struct Target *t) {

    t->prevX = t->xPos;
    t->prevY = t->yPos;

    t->xPos += t->xVelocity;
    t->yPos += t->yVelocity;

    if (t->xPos <= 0 || t->xPos >= (160 - 16)) {
        t->xVelocity *= -1;
        // Correct position so it doesn't get stuck in the wall
        if(t->xPos < 0) t->xPos = 0;
        if(t->xPos > 144) t->xPos = 144;
    }
    
    if (t->yPos <= 30 || t->yPos >= 127) { // 15 accounts for top UI/Score area
        t->yVelocity *= -1;
        if(t->yPos < 15) t->yPos = 15;
        if(t->yPos > 127) t->yPos = 127;
    }
}

